#!/usr/bin/env node
/**
 * Rút gọn ref-patterns.js của KanjiCanvas (https://github.com/asdfjkl/kanjicanvas, MIT).
 *
 * Bản gốc ~6,7 MB vì mỗi tọa độ có 14–15 chữ số thập phân. Mẫu nét đã chuẩn hóa về khung 256×256,
 * nên làm tròn còn 1 chữ số thập phân không ảnh hưởng tới nhận dạng (đã so top 10 của nhiều bộ nét thử
 * giữa bản gốc và bản rút gọn: trùng khớp).
 *
 * Cách chạy:
 *   curl -L -o /tmp/ref-patterns.js https://raw.githubusercontent.com/asdfjkl/kanjicanvas/master/docs/resources/javascript/ref-patterns.js
 *   node scripts/compact-ref-patterns.mjs /tmp/ref-patterns.js
 * Kết quả: src/vendor/kanjicanvas/ref-patterns.js (giữ đúng định dạng `KanjiCanvas.refPatterns = [...]`).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const src = process.argv[2]
if (!src) {
  console.error('Cách dùng: node scripts/compact-ref-patterns.mjs <ref-patterns.js gốc>')
  process.exit(1)
}

// Chạy file gốc trong sandbox riêng: nó chỉ gán KanjiCanvas.refPatterns.
const sandbox = { KanjiCanvas: {} }
vm.runInNewContext(readFileSync(src, 'utf8'), sandbox, { timeout: 60_000 })
const patterns = sandbox.KanjiCanvas.refPatterns
if (!Array.isArray(patterns) || patterns.length === 0) throw new Error('Không đọc được KanjiCanvas.refPatterns')

const round = (v) => Math.round(v * 10) / 10
const out = patterns.map(([ch, count, strokes]) => {
  if (typeof ch !== 'string' || strokes.length !== count) throw new Error(`Mẫu hỏng: ${ch}`)
  return [ch, count, strokes.map((s) => s.map(([x, y]) => [round(x), round(y)]))]
})

const header = `/*
 * Reference stroke patterns from KanjiCanvas — https://github.com/asdfjkl/kanjicanvas
 * Copyright (c) 2019 Dominik Klein, Kanji Canvas. MIT License (see LICENSE.TXT, backlink above).
 * Source: docs/resources/javascript/ref-patterns.js (commit a9214105f156def3b96930e5fcf10b7652b7a1f7).
 * Modified for Kotonoha: coordinates rounded to 1 decimal place, test vectors removed
 * (generated by scripts/compact-ref-patterns.mjs). ${out.length} patterns.
 */
`
const body = `KanjiCanvas.refPatterns = [\n${out.map((p) => JSON.stringify(p)).join(',\n')}\n];\n`
const target = resolve(dirname(fileURLToPath(import.meta.url)), '../src/vendor/kanjicanvas/ref-patterns.js')
writeFileSync(target, header + body)
console.log(`${out.length} mẫu → ${target} (${(Buffer.byteLength(header + body) / 1024).toFixed(0)} KB)`)
